USE Biblioteca;
-- 1
SELECT TITULO,ANIO FROM LIBROS ORDER BY ANIO ASC;
-- 2
SELECT NOMBRES,APELLIDOS,EDAD FROM ESTUDIANTES WHERE EDAD>25;
-- 3
SELECT TITULO,ANIO FROM LIBROS WHERE ID_EDIT=3;
-- 4
SELECT * FROM AUTORES WHERE APELLIDOS LIKE 'M%';
-- 5
SELECT NOMBRES,APELLIDOS FROM FUNCIONARIOS WHERE SALUD<>'Buena';
-- 6
SELECT l.TITULO,a.NOMBRES,a.APELLIDOS FROM LIBROS l JOIN AUTORES a ON a.RUT_AUTOR=l.RUT_AUTOR;
-- 7
SELECT p.FECHA_P,CONCAT(e.NOMBRES,' ',e.APELLIDOS) AS ESTUDIANTE,l.TITULO,CONCAT(f.NOMBRES,' ',f.APELLIDOS) AS FUNCIONARIO FROM PRESTAMO p JOIN ESTUDIANTES e ON e.RUT_EST=p.RUT_EST JOIN LIBROS l ON l.COD_LIBRO=p.COD_LIBRO JOIN FUNCIONARIOS f ON f.RUT_FUNC=p.RUT_FUNC;
-- 8: ciudad del campus de la carrera, no domicilio del estudiante
SELECT e.NOMBRES,c.NOMBRE AS CARRERA,ci.NOMBRE AS CIUDAD_ESTUDIOS FROM ESTUDIANTES e JOIN CARRERAS c ON c.ID_CARRERA=e.ID_CARRERA JOIN CAMPUS ca ON ca.ID_CAMPUS=c.ID_CAMPUS JOIN CIUDAD ci ON ci.ID_CIUDAD=ca.ID_CIUDAD;
-- 9
SELECT l.TITULO,ed.NOMBRE AS EDITORIAL,ed.PAIS FROM LIBROS l JOIN EDITORIALES ed ON ed.ID_EDIT=l.ID_EDIT;
-- 10
SELECT l.TITULO,b.BIBLIOTECA FROM LIBROS l JOIN BIBLIOTECA b ON b.ID_BIBLIO=l.ID_BIBLIO;
-- 11
SELECT t.TIPO_P,COUNT(l.COD_LIBRO) AS CANTIDAD FROM TIPO t LEFT JOIN LIBROS l ON l.ID_TIPO=t.ID_TIPO GROUP BY t.ID_TIPO,t.TIPO_P;
-- 12
SELECT c.NOMBRE AS CARRERA,ROUND(AVG(e.EDAD),2) AS EDAD_PROMEDIO FROM CARRERAS c LEFT JOIN ESTUDIANTES e ON e.ID_CARRERA=c.ID_CARRERA GROUP BY c.ID_CARRERA,c.NOMBRE;
-- 13
SELECT CONCAT(f.NOMBRES,' ',f.APELLIDOS) AS FUNCIONARIO,COUNT(p.COD_LIBRO) AS PRESTAMOS FROM FUNCIONARIOS f LEFT JOIN PRESTAMO p ON p.RUT_FUNC=f.RUT_FUNC GROUP BY f.RUT_FUNC,f.NOMBRES,f.APELLIDOS ORDER BY PRESTAMOS DESC;
-- 14
SELECT a.RUT_AUTOR,a.NOMBRES,a.APELLIDOS,COUNT(l.COD_LIBRO) AS LIBROS FROM AUTORES a JOIN LIBROS l ON l.RUT_AUTOR=a.RUT_AUTOR GROUP BY a.RUT_AUTOR,a.NOMBRES,a.APELLIDOS HAVING COUNT(l.COD_LIBRO)>1;
-- 15: el esquema NO almacena ciudad de residencia del estudiante; se interpreta como ciudad del campus.
SELECT ci.NOMBRE AS CIUDAD_CAMPUS,COUNT(e.RUT_EST) AS ESTUDIANTES FROM CIUDAD ci JOIN CAMPUS ca ON ca.ID_CIUDAD=ci.ID_CIUDAD JOIN CARRERAS c ON c.ID_CAMPUS=ca.ID_CAMPUS LEFT JOIN ESTUDIANTES e ON e.ID_CARRERA=c.ID_CARRERA GROUP BY ci.ID_CIUDAD,ci.NOMBRE;
-- 16: incluye empates
SELECT TITULO,ANIO FROM LIBROS WHERE ANIO=(SELECT MIN(ANIO) FROM LIBROS);
-- 17
SELECT e.* FROM ESTUDIANTES e LEFT JOIN PRESTAMO p ON p.RUT_EST=e.RUT_EST WHERE p.RUT_EST IS NULL;
-- 18
SELECT l.TITULO FROM LIBROS l LEFT JOIN PRESTAMO p ON p.COD_LIBRO=l.COD_LIBRO WHERE p.COD_LIBRO IS NULL;
-- 19: rango de mes calendario anterior, también en enero
SELECT * FROM PRESTAMO WHERE FECHA_P>=DATE_FORMAT(CURDATE()-INTERVAL 1 MONTH,'%Y-%m-01') AND FECHA_P<DATE_FORMAT(CURDATE(),'%Y-%m-01');
-- 20
SELECT l.TITULO,COUNT(p.COD_LIBRO) AS VECES_PRESTADO FROM LIBROS l JOIN PRESTAMO p ON p.COD_LIBRO=l.COD_LIBRO GROUP BY l.COD_LIBRO,l.TITULO ORDER BY VECES_PRESTADO DESC,l.TITULO LIMIT 3;
