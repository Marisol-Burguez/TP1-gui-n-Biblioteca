USE Biblioteca;
CREATE OR REPLACE VIEW VW_PRESTAMOS_DETALLE AS
SELECT p.FECHA_P AS FECHA_PRESTAMO,CONCAT(e.NOMBRES,' ',e.APELLIDOS) AS ESTUDIANTE,l.TITULO AS LIBRO,CONCAT(f.NOMBRES,' ',f.APELLIDOS) AS FUNCIONARIO,c.NOMBRE AS CARRERA
FROM PRESTAMO p JOIN ESTUDIANTES e ON e.RUT_EST=p.RUT_EST JOIN LIBROS l ON l.COD_LIBRO=p.COD_LIBRO JOIN FUNCIONARIOS f ON f.RUT_FUNC=p.RUT_FUNC JOIN CARRERAS c ON c.ID_CARRERA=e.ID_CARRERA;
-- El diagrama no vincula BIBLIOTECA a CIUDAD; no se inventa una ciudad.
CREATE OR REPLACE VIEW VW_LIBROS_POR_BIBLIOTECA AS
SELECT b.BIBLIOTECA AS NOMBRE_BIBLIOTECA,COUNT(l.COD_LIBRO) AS TOTAL_LIBROS FROM BIBLIOTECA b LEFT JOIN LIBROS l ON l.ID_BIBLIO=b.ID_BIBLIO GROUP BY b.ID_BIBLIO,b.BIBLIOTECA;
