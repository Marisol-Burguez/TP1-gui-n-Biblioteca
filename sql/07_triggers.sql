USE Biblioteca;
CREATE TABLE IF NOT EXISTS AUDITORIA_PRESTAMOS (ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,RUT_EST VARCHAR(20) NOT NULL,COD_LIBRO INT NOT NULL,FECHA_REGISTRO DATETIME NOT NULL,ACCION VARCHAR(100) NOT NULL);
DELIMITER $$
CREATE TRIGGER TR_AUDITAR_PRESTAMO AFTER INSERT ON PRESTAMO FOR EACH ROW
BEGIN
 INSERT INTO AUDITORIA_PRESTAMOS(RUT_EST,COD_LIBRO,FECHA_REGISTRO,ACCION) VALUES(NEW.RUT_EST,NEW.COD_LIBRO,NOW(),'NUEVO PRÉSTAMO');
END$$
-- MySQL requiere un trigger para INSERT y otro para UPDATE.
CREATE TRIGGER TR_VALIDAR_EDAD_ESTUDIANTE BEFORE INSERT ON ESTUDIANTES FOR EACH ROW
BEGIN
 IF NEW.EDAD<17 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Error: el estudiante debe tener al menos 17 años'; END IF;
END$$
CREATE TRIGGER TR_VALIDAR_EDAD_ESTUDIANTE_UPDATE BEFORE UPDATE ON ESTUDIANTES FOR EACH ROW
BEGIN
 IF NEW.EDAD<17 THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Error: el estudiante debe tener al menos 17 años'; END IF;
END$$
DELIMITER ;
